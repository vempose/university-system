package university.enums;

/// Academic degree levels offered by the university.
///
/// Used in `Major` and `Enrollment` to track what degree
/// a student is working toward.
public enum DegreeType {
    /// Undergraduate degree (4 years)
    BACHELOR,
    /// Graduate degree (2 years)
    MASTER,
    /// Doctorate (research-based)
    PHD,
}

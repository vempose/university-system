package university.enums;

/// Topics used to tag and filter university news.
///
/// Each `News` article gets assigned one so readers
/// can find what interests them.
public enum NewsTopic {
    /// Research publications and discoveries
    RESEARCH,
    /// Academic announcements (deadlines, exams, etc.)
    ACADEMIC,
    /// Upcoming events and activities
    EVENT,
    /// Everything else
    GENERAL,
}

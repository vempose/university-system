package university.enums;

/// Academic ranks a teacher can hold.
///
/// Mirrors the typical university promotion ladder
/// from junior teaching roles to full professor.
public enum TeacherPosition {
    /// Entry-level teaching assistant
    TUTOR,
    /// Lecturer
    LECTOR,
    /// Senior lecturer with more responsibility
    SENIOR_LECTOR,
    /// Highest rank (full professor)
    PROFESSOR,
}
